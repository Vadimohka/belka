import json, random, sys
from pathlib import Path

random.seed(42)
seen = set()
T, V, E = [], [], []
def add(s,m,c):
    h=hash(json.dumps(m,ensure_ascii=False,sort_keys=True))
    if h in seen: return
    seen.add(h)
    (T if s=='t' else V if s=='v' else E).append((m,c))
def w(p,d):
    Path(p).parent.mkdir(parents=True,exist_ok=True)
    with open(p,'w',encoding='utf-8') as f:
        for m,_ in d: f.write(json.dumps(m,ensure_ascii=False)+'\n')

def fill(cat, pairs, target):
    """Add to train, deduping. Fill to target by cycling through pairs."""
    added = 0
    idx = 0
    while added < target:
        q, txt = pairs[idx % len(pairs)]
        old = len(seen)
        add('t', [{"role":"user","content":q},{"role":"assistant","content":txt}], cat)
        if len(seen) > old: added += 1
        idx += 1
    return added

