def build_entry(q, a, category):
    return {"messages": [{"role": "user", "content": q}, {"role": "assistant", "content": a}],
            "category": category, "source": "manual_curated_sft_v3", "synthetic": True,
            "license": "manual_curated_research", "split": "train"}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pack-dir', default=os.environ.get('PACK_DIR', '.'))
    ap.add_argument('--train-out', default='seed_sft/sft_v3_train.be.jsonl')
    ap.add_argument('--val-out', default='seed_sft/sft_v3_val.be.jsonl')
    ap.add_argument('--eval-out', default='eval/language_lock_eval_v3.be.jsonl')
    ap.add_argument('--report', default='reports/sft_v3/sft_v3_dataset_report.json')
    args = ap.parse_args()
    pack = Path(args.pack_dir).resolve()

    entries = []
    for cat, pairs in CATEGORIES.items():
        for q, a in pairs:
            entries.append(build_entry(q, a, cat))

    random.shuffle(entries)

    # Split: 80% train, 10% val, 10% eval (held-out)
    n = len(entries)
    n_val = max(n * 10 // 100, 20)
    n_eval = max(n * 10 // 100, 20)
    train = entries[:n - n_val - n_eval]
    val = entries[n - n_val - n_eval:n - n_eval]
    eval_held = entries[n - n_eval:]

    for path, data, split_name in [
        (args.train_out, train, 'train'),
        (args.val_out, val, 'val'),
        (args.eval_out, eval_held, 'eval')
    ]:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, 'w', encoding='utf-8') as f:
            for e in data:
                e['split'] = split_name
                f.write(json.dumps(e['messages'], ensure_ascii=False) + '\n')
        print(f'{split_name}: {len(data)} examples -> {p}')

    report = {'total': n, 'train': len(train), 'val': len(val), 'eval_held': len(eval_held),
              'categories': {c: len([e for e in entries if e['category'] == c]) for c in sorted(CATEGORIES)}}
    Path(args.report).parent.mkdir(parents=True, exist_ok=True)
    json.dump(report, open(args.report, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f'Report: {args.report}')
    print(f'TOTAL={n}')

if __name__ == '__main__':
    main()
