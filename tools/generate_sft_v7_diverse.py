def add(split, msgs, cat):
    h = hash(json.dumps(msgs, ensure_ascii=False, sort_keys=True))
    if h in seen: return False
    seen.add(h)
    bucket = train if split == 'train' else val if split == 'val' else eval_set
    bucket.append((msgs, cat))
    return True

def write_jsonl(path, items):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        for msgs, _ in items: f.write(json.dumps(msgs, ensure_ascii=False) + '\n')

def fill(split, pairs, cat, target):
    added = 0
    for q, a in pairs:
        if added >= target: break
